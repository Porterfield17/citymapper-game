create table if not exists public.game_content (
  id text primary key check (id = 'published'),
  cities jsonb not null default '[]'::jsonb,
  daily_games jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.game_content enable row level security;

grant select on public.game_content to anon, authenticated;
revoke insert, update, delete on public.game_content from anon, authenticated;
grant all on public.game_content to service_role;

create table if not exists public.game_content_revisions (
  revision_id bigint generated by default as identity primary key,
  source_updated_at timestamptz not null,
  archived_at timestamptz not null default now(),
  cities jsonb not null,
  daily_games jsonb not null
);

alter table public.game_content_revisions enable row level security;
revoke all on public.game_content_revisions from anon, authenticated;
grant all on public.game_content_revisions to service_role;

create or replace function public.archive_game_content_revision()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.game_content_revisions (source_updated_at, cities, daily_games)
  values (old.updated_at, old.cities, old.daily_games);

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

revoke all on function public.archive_game_content_revision() from public, anon, authenticated;
grant execute on function public.archive_game_content_revision() to service_role;

drop trigger if exists archive_game_content_before_update on public.game_content;
create trigger archive_game_content_before_update
  before update on public.game_content
  for each row
  when (old.cities is distinct from new.cities or old.daily_games is distinct from new.daily_games)
  execute function public.archive_game_content_revision();

drop trigger if exists archive_game_content_before_delete on public.game_content;
create trigger archive_game_content_before_delete
  before delete on public.game_content
  for each row
  execute function public.archive_game_content_revision();

insert into public.game_content_revisions (source_updated_at, cities, daily_games)
select updated_at, cities, daily_games
from public.game_content
where id = 'published'
  and not exists (
    select 1
    from public.game_content_revisions
    where source_updated_at = game_content.updated_at
  );

